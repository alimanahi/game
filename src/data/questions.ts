// Helper to get questions for quick game (10 questions, prioritized unviewed)
export function getQuestionsForGame(
  count: number = 10,
  viewedIds: string[] = [],
  categoryFilter?: string
): Question[] {
  let pool = [...QUESTIONS_DATASET];

  if (categoryFilter) {
    pool = pool.filter((q) => q.category === categoryFilter);
  }

  // Prioritize unviewed questions
  const unviewed = pool.filter((q) => !viewedIds.includes(q.id));
  const viewed = pool.filter((q) => viewedIds.includes(q.id));

  // Shuffle arrays
  const shuffle = <T>(arr: T[]): T[] => [...arr].sort(() => Math.random() - 0.5);

  const selected: Question[] = [];
  const shuffledUnviewed = shuffle(unviewed);
  const shuffledViewed = shuffle(viewed);

  for (const q of shuffledUnviewed) {
    if (selected.length < count) selected.push(q);
  }

  if (selected.length < count) {
    for (const q of shuffledViewed) {
      if (selected.length < count) selected.push(q);
    }
  }

  return selected;
}

// Get deterministic 10 questions for daily challenge based on today's date
export function getDailyChallengeQuestions(dateStr: string): Question[] {
  // Use date string as simple seed
  let hash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    hash = (hash << 5) - hash + dateStr.charCodeAt(i);
    hash |= 0;
  }
  const positiveHash = Math.abs(hash);

  const pool = [...QUESTIONS_DATASET];
  const count = 10;
  const picked: Question[] = [];

  for (let i = 0; i < count; i++) {
    const idx = (positiveHash + i * 7) % pool.length;
    picked.push(pool[idx]);
  }

  return picked;
}
